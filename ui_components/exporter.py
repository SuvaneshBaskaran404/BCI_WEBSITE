def _model_lines(p):
    clf = p["classifier"]
    if clf == MDM_NAME:
        return [f'    return make_pipeline(Covariances(estimator="lwf"), MDM(metric="{p["metric"]}"))']
    feature_lines = {
        "CSP": ["    features = CSP(n_components=6, log=True)"],
        "Riemann Tangent Space": [
            '    features = make_pipeline(Covariances(estimator="lwf"), TangentSpace(metric="riemann"))'],
        "Raw ERP (flattened)": [
            "    features = make_pipeline(FunctionTransformer(flatten_erp), StandardScaler())"],
    }[p["feature"]]
    if clf == LDA:
        clf_line = f'    classifier = LinearDiscriminantAnalysis(solver="lsqr", shrinkage={p["shrinkage"]})'
    elif clf == SVM:
        clf_line = (f'    classifier = CalibratedClassifierCV(SVC(C={p["C"]}, kernel="{p["kernel"]}"), '
                    'method="sigmoid", cv=3)')
    elif clf == RF:
        clf_line = "    classifier = RandomForestClassifier(n_estimators=200, random_state=0)"
    else:
        raise ValueError(f"Unknown classifier: {clf}")
    return feature_lines + [clf_line, "    return make_pipeline(features, classifier)"]


def build_pipeline_script(params):
    """Return the source of a runnable MNE + scikit-learn + pyRiemann script."""
    body = "\n".join(_model_lines(params))
    return SCRIPT_TEMPLATE.replace("__PARAMS__", repr(params)).replace("__MODEL_LINES__", body)


def build_config_json(params):
    return json.dumps({"format_version": 1, "parameters": params}, indent=2)
